"""Cross-run MGE alert generator.

The alert pipeline runs in three phases:

1. Ingest the current run into the repository (plasmids + integrons + host
   metadata). This grows the repository before matching so that re-running
   the alerts on the same run is idempotent.
2. For every MGE in the current run, search the *prior* repository state for
   matches (plasmid: two-level tuple + ANI; integron: Jaccard on cassette
   gene set).
3. Apply the relevance filter (AMR or virulence genes carried, with priority
   escalation for carbapenemases / mcr / hypervirulence and for cross-species
   transfer) and emit ``alerts.tsv``.

This file is the scaffold for P0; the matching and reporting bodies land in
P3 / P4.
"""

