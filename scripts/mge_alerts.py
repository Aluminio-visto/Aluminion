# Regex that strips parenthetical identity/coverage annotations such as
# " (99.50)" or " (100.00;98.95)". It is applied BEFORE splitting on [;,]
# because the annotation itself can contain those separators — splitting first
# shatters "acrB (98.19;100.00)" into the orphan fragments "acrB (98.19" and
# "100.00)". Stripping every "( ... )" group first avoids that.
_SCORE_ANNOT_RE = re.compile(r"\([^)]*\)")


def _split_gene_string(s: str) -> set[str]:
    """Normalize an AMR/VIR gene field into a set of bare gene names.

    Handles Copla's semicolon list (``"OXA-48;CTX-M-15"``), the per-plasmid
    ``Vir`` column (bare semicolon list), and the comma-separated list with
    score annotations emitted by parser.py for VFDB
    (``"fimH (98.50), acrB (98.19;100.00)"``).
    """
    if not s or s == "-":
        return set()
    s = _SCORE_ANNOT_RE.sub("", s)  # drop "(...)" groups (may contain ; or ,)
    parts = re.split(r"[;,]", s)
    out: set[str] = set()
    for p in parts:
        p = p.strip()
        if p and p != "-":
            out.add(p)
    return out


def _species_token(s: str) -> str:
    """Extract the bare species (or genus) epithet from a Majority_* field.

    ``data_analysis.tsv`` stores values such as ``"pneumoniae (95.3%)"`` or
    ``"Klebsiella (95.3%)"``; we keep only the first whitespace-delimited
    token so that cross-species comparisons are stable.
    """
    if not s:
        return ""
    return s.strip().split()[0]


def _is_cross_species(match: dict) -> bool:
    """True if the current and prior hosts belong to different species OR
    different genera. Returns False when either side has unknown taxonomy
    (empty species and empty genus) — conservative: no taxonomic info means
    we cannot claim a cross-species event.
    """
    cur = match.get("current_host", {})
    pri = match.get("repo_host", {})
    cur_sp = _species_token(cur.get("species", ""))
    pri_sp = _species_token(pri.get("species", ""))
    cur_gn = _species_token(cur.get("genus", ""))
    pri_gn = _species_token(pri.get("genus", ""))

    species_known = cur_sp and pri_sp
    genus_known = cur_gn and pri_gn
    if not species_known and not genus_known:
        return False
    if species_known and cur_sp != pri_sp:
        return True
    if genus_known and cur_gn != pri_gn:
        return True
    return False


def _format_genes(values) -> str:
    """Join a gene iterable with semicolons in a stable order for the TSV."""
    if isinstance(values, str):
        return values
    return ";".join(sorted({v for v in values if v}))


def _build_alert_row(
    *,
    category: str,
    priority: str,
    current_isolate_id: str,
    current_meta: dict,
    current_host: dict,
    mge_type: str,
    cross_species: bool,
    priority_info: dict,
    amr_genes: set[str],
    vir_genes: set[str],
    hits: list[dict],
) -> dict:
    """Assemble a single alerts.tsv row — one alert == one current MGE.

    ``hits`` is the list of prior repository matches grouped under this MGE
    (each a dict produced in :func:`emit_alerts`). It is serialized to JSON in
    ``match_hits_json``; the HTML reporter renders the hits stacked inside one
    card instead of emitting a separate card per repository match.
    """
    if mge_type == "plasmid":
        ptu = current_meta.get("ptu", "")
        mob = current_meta.get("mob", "")
        mpf = current_meta.get("mpf", "")
        rep = current_meta.get("rep", "")
        size = current_meta.get("size", "")
        gene_set = ""
    else:
        ptu = mob = mpf = rep = ""
        size = current_meta.get("size", "")
        gene_set = current_meta.get("gene_set_json", "[]")

    # Best match level across the grouped hits (identity beats type for
    # plasmids; integrons carry a "jaccard:NN" string we surface verbatim).
    levels = [h.get("match_level", "") for h in hits]
    if any(lv == "identity" for lv in levels):
        best_level = "identity"
    elif any(lv == "type" for lv in levels):
        best_level = "type"
    else:
        best_level = levels[0] if levels else ""

    return {
        "alert_category": category,
        "priority": priority,
        "mge_type": mge_type,
        "current_host_uid": current_host.get("host_uid", ""),
        # current_lab_id intentionally omitted (see ALERTS_COLUMNS comment).
        "current_isolate_id": current_isolate_id,
        "current_species": current_host.get("species", ""),
        "current_mlst": current_host.get("mlst", ""),
        "n_hits": str(len(hits)),
        "match_level": best_level,
        "cross_species": "yes" if cross_species else "no",
        "ptu": ptu,
        "mob": mob,
        "mpf": mpf,
        "rep": rep,
        "size": str(size) if size != "" else "",
        "gene_set": gene_set,
        "amr_genes": ";".join(sort_amr_genes(amr_genes)),
        "vir_genes": _format_genes(vir_genes),
        "priority_genes_detected": ";".join(sorted(set(priority_info.get("matched", [])))),
        "priority_categories": ",".join(priority_info.get("categories", [])),
        "match_hits_json": json.dumps(hits, ensure_ascii=False),
    }


def _build_hit(match: dict) -> dict:
    """Project one match record into the compact per-hit dict stored in JSON.

    Every field is coerced to ``str`` so the JSON round-trip is type-stable:
    ``repo_row["size"]`` is an ``int`` when the match came from the tuple
    branch (which casts ``df_t["size"].astype(int)`` to filter by the size
    band) but a plain string when it came from the ANI branch — leading to
    a mixed ``"size": "65530"`` vs ``"size": 60569`` schema inside the
    serialized JSON, which then crashed ``alerts_reporter._field`` because
    ``html.escape`` cannot ``.replace`` an int. Stringifying here also future-
    proofs the reporter against any other column whose dtype may vary.
    """
    repo_row = match.get("repo_row", {}) or {}
    repo_host = match.get("repo_host", {}) or {}

    def _s(v):
        # Treat NaN / None as the empty string so blank cells stay blank in the
        # rendered HTML instead of showing the literal string "nan".
        if v is None:
            return ""
        try:
            if pd.isna(v):  # pandas / numpy NaN
                return ""
        except (TypeError, ValueError):
            pass
        return str(v)

    return {
        "match_uid": _s(match.get("match_uid", "")),
        "match_level": _s(match.get("match_level", "")),
        "previous_host_uid": _s(repo_row.get("host_uid", "")),
        "previous_isolate_id": _s(repo_host.get("isolate_id", "") or repo_row.get("sample_id", "")),
        # Prefer the recorded sequencing date; fall back to the run name (a date
        # in the lab's convention) so older repositories still show something.
        "previous_seq_date": _s(repo_host.get("seq_date", "") or repo_host.get("run_name", "") or repo_row.get("run_name", "")),
        "previous_species": _s(repo_host.get("species", "")),
        "previous_mlst": _s(repo_host.get("mlst", "")),
        "previous_ptu": _s(repo_row.get("ptu", "")),
        "previous_rep": _s(repo_row.get("rep", "")),
        "previous_mob": _s(repo_row.get("mob", "")),
        "previous_mpf": _s(repo_row.get("mpf", "")),
        "previous_size": _s(repo_row.get("size", "")),
        "previous_amr_genes": ";".join(sort_amr_genes(_split_gene_string(repo_row.get("amr_genes", "")))),
        "cross_species": "yes" if _is_cross_species(match) else "no",
        "ingested_at": _s(repo_row.get("ingested_at", "")),
    }


def emit_alerts(
    matches: list[dict],
    args: argparse.Namespace,
    repo: Repository,
) -> Path:
    """Build ``alerts.tsv`` from match records and optional NEW_PRIORITY scan.

    Returns the path of the written file. Even when no alerts fire, the file
    is written with the header row so downstream consumers (HTML reporter,
    notification systems) can always rely on its presence.
    """
    rows: list[dict] = []

    # ----- RECURRENT_RELEVANT ----------------------------------------------
    # Group every (current_MGE -> repo_hit) match record by the current MGE so
    # the analyst sees ONE alert per recurrent element, listing all prior
    # repository occurrences. A prevalent plasmid such as pOXA-48 can match
    # dozens of priors; collapsing them into a single card (with the hits
    # stacked) keeps the report readable.
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for m in matches:
        key = (m["current_isolate_id"], m["current_contig"], m["mge_type"])
        groups[key].append(m)

    for (isolate_id, _contig, mge_type), ms in groups.items():
        ref = ms[0]  # current-MGE fields are identical across the group
        amr = _split_gene_string(ref["current_meta"].get("amr_genes", ""))
        vir = _split_gene_string(ref["current_meta"].get("vir_genes", ""))
        if not amr and not vir:
            # The MGE is not epidemiologically relevant (no AMR / no virulence).
            continue

        info = classify_priority(amr | vir)
        any_cross = any(_is_cross_species(m) for m in ms)
        # Priority escalation: HIGH if a HIGH-priority gene fires or ANY of the
        # grouped hits crosses a species boundary.
        priority = "high" if (info["priority"] == "high" or any_cross) else "medium"

        # One hit entry per matched repository UID, newest first (by ingestion).
        hits = sorted(
            (_build_hit(m) for m in ms),
            key=lambda h: h["ingested_at"],
            reverse=True,
        )

        rows.append(_build_alert_row(
            category="RECURRENT_RELEVANT",
            priority=priority,
            current_isolate_id=isolate_id,
            current_meta=ref["current_meta"],
            current_host=ref["current_host"],
            mge_type=mge_type,
            cross_species=any_cross,
            priority_info=info,
            amr_genes=amr,
            vir_genes=vir,
            hits=hits,
        ))

    # ----- NEW_PRIORITY ----------------------------------------------------
    if args.alert_new_priority:
        matched_keys = {(m["current_isolate_id"], m["current_contig"]) for m in matches}
        inputs = _load_run_inputs(args.run_dir)
        run_name: str = args.run_name

        # Plasmids: any current plasmid not matched in repo, carrying a
        # HIGH-priority gene (carbapenemase / mcr / hypervirulence) and
        # passing the size cut.
        for _, row in inputs["copla"].iterrows():
            isolate_id = row.get("Sample", "")
            contig = row.get("Contig", "")
            if not isolate_id or not contig:
                continue
            if (isolate_id, contig) in matched_keys:
                continue
            try:
                size = int(row.get("Size", "0") or 0)
            except ValueError:
                size = 0
            if size and size < args.min_plasmid_size:
                continue

            amr = _split_gene_string(row.get("AbR", ""))
            vir = _split_gene_string(row.get("Vir", ""))
            info = classify_priority(amr | vir)
            if info["priority"] != "high":
                continue

            current_host = {
                "host_uid": make_host_uid(run_name, isolate_id),
                "lab_id": "",
                "isolate_id": isolate_id,
                "species": "",
                "mlst": "",
            }
            # Backfill from data_analysis.tsv when present (same shape as
            # run_matching builds it).
            da = inputs["data_analysis"]
            da_row = da[da["ID"] == isolate_id]
            if not da_row.empty:
                r0 = da_row.iloc[0]
                current_host["lab_id"] = r0.get("Lab_id", "")
                current_host["species"] = r0.get("Majority_species", "")
                current_host["mlst"] = r0.get("MLST", "")

            rows.append(_build_alert_row(
                category="NEW_PRIORITY",
                priority="high",
                current_isolate_id=isolate_id,
                current_meta={
                    "ptu": row.get("PTU", ""),
                    "rep": row.get("Rep", ""),
                    "mob": row.get("MOB", ""),
                    "mpf": row.get("MPF", ""),
                    "size": size,
                },
                current_host=current_host,
                mge_type="plasmid",
                cross_species=False,
                priority_info=info,
                amr_genes=amr,
                vir_genes=vir,
                hits=[],
            ))

        # Integrons: any current integron not matched in repo whose cassette
        # gene set carries a HIGH-priority gene.
        for _, row in inputs["integrons"].iterrows():
            isolate_id = row.get("Sample", "")
            contig = row.get("Pl/Chr", "")
            if not isolate_id or not contig:
                continue
            if (isolate_id, contig) in matched_keys:
                continue
            gene_set = _parse_cassette_gene_set(row)
            if not gene_set:
                continue

            info = classify_priority(gene_set)
            if info["priority"] != "high":
                continue

            try:
                start = int(row.get("Start", "0") or 0)
                end = int(row.get("End", "0") or 0)
            except ValueError:
                start = end = 0

            current_host = {
                "host_uid": make_host_uid(run_name, isolate_id),
                "lab_id": "",
                "isolate_id": isolate_id,
                "species": "",
                "mlst": "",
            }
            da_row = inputs["data_analysis"][
                inputs["data_analysis"]["ID"] == isolate_id
            ]
            if not da_row.empty:
                r0 = da_row.iloc[0]
                current_host["lab_id"] = r0.get("Lab_id", "")
                current_host["species"] = r0.get("Majority_species", "")
                current_host["mlst"] = r0.get("MLST", "")

            rows.append(_build_alert_row(
                category="NEW_PRIORITY",
                priority="high",
                current_isolate_id=isolate_id,
                current_meta={
                    "size": end - start + 1 if start and end else "",
                    "gene_set_json": serialize_gene_set(gene_set),
                },
                current_host=current_host,
                mge_type="integron",
                cross_species=False,
                priority_info=info,
                amr_genes=gene_set,
                vir_genes=set(),
                hits=[],
            ))

    # ----- Write TSV --------------------------------------------------------
    out = pd.DataFrame(rows, columns=ALERTS_COLUMNS).fillna("")
    # Stable sort: HIGH first, then MEDIUM, then by mge_type and isolate_id.
    priority_order = {"high": 0, "medium": 1}
    if not out.empty:
        out["_psort"] = out["priority"].map(priority_order).fillna(99)
        out = (
            out.sort_values(["_psort", "mge_type", "current_isolate_id"])
            .drop(columns=["_psort"])
            .reset_index(drop=True)
        )

    alerts_path: Path = args.run_dir / "alerts.tsv"
    out.to_csv(alerts_path, sep="\t", index=False)
    return alerts_path


def main(argv: list[str] | None = None) -> int:
    args = parse_arguments() if argv is None else parse_arguments()

    repo = Repository.open(args.repo)
    print(
        f"[mge_alerts] run={args.run_name}  repo={args.repo}",
        file=sys.stderr,
    )

    # Matching MUST happen before ingestion so that the current run's own
    # plasmids/integrons are not matched against themselves.
    matches = run_matching(args, repo)
    print(
        f"[mge_alerts] matching produced {len(matches)} match record(s) "
        "(grouped/filtered in P4 → alerts.tsv).",
        file=sys.stderr,
    )

    if not args.no_ingest:
        stats = run_ingestion(args, repo)
        print(
            "[mge_alerts] ingestion stats: "
            f"hosts={stats['hosts']}  plasmids={stats['plasmids']}  "
            f"plasmids_skipped_size={stats['plasmids_skipped_size']}  "
            f"plasmids_skipped_missing_fasta={stats['plasmids_skipped_missing_fasta']}  "
            f"integrons={stats['integrons']}",
            file=sys.stderr,
        )

    alerts_path = emit_alerts(matches, args, repo)
    n_alerts = sum(1 for _ in open(alerts_path)) - 1  # subtract header
    print(
        f"[mge_alerts] wrote {n_alerts} alert(s) to {alerts_path}",
        file=sys.stderr,
    )

    # HTML report — lazy import so the script still runs in environments
    # without the optional jinja templating (currently we use pure f-string
    # rendering so this is just a normal import).
    try:
        from alerts_reporter import render_alerts_html
        html_path = args.run_dir / "Alerts_Report.html"
        render_alerts_html(alerts_path, html_path, run_name=args.run_name)
        print(f"[mge_alerts] wrote HTML report to {html_path}", file=sys.stderr)
    except Exception as exc:  # report failure is non-fatal
        print(f"[mge_alerts] HTML report generation failed: {exc}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main())
