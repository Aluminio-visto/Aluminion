def _parse_cassette_gene_set(row: pd.Series) -> set[str]:
    """Extract the unique gene names from an integron_summary.csv row.

    Handles TWO formats produced by ``integron_parser.py`` over the lifetime
    of the lab:

    1. **Current format** (since the parser switched to
       ``", ".join(cassettes)``): each ``Cassette N`` cell is a bare,
       comma-separated string of gene names, e.g. ``"blaOXA-1, NA, NA, NA"``,
       or a single bare token like ``"aac(6')-Ib-D181Y"``.
    2. **Legacy format** (still found in older repository entries and in the
       ``examples/`` files): each cell is a Python list literal like
       ``"['blaOXA-1_1', 'aac(6\\')Ib-cr_1']"``; items may further carry a
       ``"<gene>;<description>"`` shape — we keep only ``<gene>``.

    Distinguishing the two: ``ast.literal_eval`` only succeeds on the legacy
    form (bare strings like ``blaGES-13`` are NOT valid Python literals).
    Falling through to ``split(',')`` on parse failure handles the current
    format. Results are passed through :func:`normalize_gene_set` so the
    ``"NA"`` placeholder rows and Prokka per-hit ``_<digits>`` suffixes do
    not pollute the resulting set.

    Until this dual-format support landed, the parser silently dropped every
    cassette under the current format — leaving the entire integron repository
    indexed with empty ``gene_set_json``. That broke Jaccard matching for
    every cross-run integron, regardless of how identical the cassettes were.
    """
    raw_items: list[str] = []
    for col, val in row.items():
        if not isinstance(col, str) or not col.startswith("Cassette "):
            continue
        if not val or val == "-":
            continue
        items: list[str]
        try:
            parsed = ast.literal_eval(val)
        except (ValueError, SyntaxError):
            # Current format: bare comma-separated string.
            items = val.split(",")
        else:
            # Legacy format: list literal. Single non-list values (rare)
            # are wrapped so the loop body stays uniform.
            if isinstance(parsed, list):
                items = [str(x) for x in parsed]
            else:
                items = [str(parsed)]
        for item in items:
            # Both formats may carry "gene;description" inside an item;
            # take the leading token as the gene-name candidate.
            name = item.split(";")[0].strip()
            if name:
                raw_items.append(name)
    return normalize_gene_set(raw_items)


def _load_seq_dates(run_dir: Path) -> dict[str, str]:
    """Map ``isolate_id -> sequencing date`` from the per-run data_seq.tsv
    snapshot (written by lab_db_updater.py just before this step). Empty when
    the file or its columns are absent (older runs / --skip paths); callers
    fall back to the run name, which is itself a date in the lab's convention.
    """
    path = run_dir / "data_seq.tsv"
    if not path.exists():
        return {}
    try:
        df = pd.read_csv(path, sep="\t", dtype=str).fillna("")
    except Exception:
        return {}
    if "ID" not in df.columns or "Seq_date" not in df.columns:
        return {}
    return dict(zip(df["ID"].astype(str), df["Seq_date"].astype(str)))


def _load_run_inputs(run_dir: Path) -> dict:
    """Load the run-level inputs that both matching and ingestion need.

    Returns a dict ``{data_analysis, copla, integrons}``. Missing optional
    inputs (copla, integron_summary) yield empty frames; only
    ``data_analysis.tsv`` is required. Per-plasmid virulence genes are read
    straight from the ``Vir`` column of copla_modif.csv (added by parser.py),
    so virulence is attributed to the specific plasmid carrying it rather than
    smeared from the whole-genome VFDB profile.

    Host metadata is merged from two sources:
      * ``data_analysis.tsv`` provides ``Lab_id``, ``ID``, ``Barcode`` and
        ``Strain`` (the lab-tracking columns).
      * ``taxonomy.csv``      provides ``Majority_genus``, ``Majority_species``,
        ``Subspecies``, ``MLST``, ``Serotype``, ``KO_locus``, ``AMRscore``
        and ``VIRscore`` — these are typically populated by parser.py while
        ``data_analysis.tsv`` keeps them as a placeholder until
        lab_db_updater.py merges them in the cumulative DB.

    The merge is a left-join on ``data_analysis.ID == taxonomy.Sample`` so
    every sample present in ``data_analysis.tsv`` keeps a row even when
    taxonomy.csv has not been emitted yet (e.g. in --skip-typing runs).
    """
    data_analysis_path = run_dir / "data_analysis.tsv"
    if not data_analysis_path.exists():
        raise FileNotFoundError(
            f"{data_analysis_path} not found. Run parser.py first or pass a "
            "different --run-dir."
        )
    data_analysis = pd.read_csv(data_analysis_path, sep="\t", dtype=str).fillna("")

    taxonomy_path = run_dir / "taxonomy.csv"
    if taxonomy_path.exists():
        taxonomy = pd.read_csv(taxonomy_path, sep=",", dtype=str).fillna("")
        # Columns where taxonomy.csv is authoritative — overwrite the
        # data_analysis placeholder values when both exist.
        tax_cols = [
            "Majority_genus", "Majority_species", "Subspecies", "MLST",
            "Serotype", "KO_locus", "AMRscore", "VIRscore",
        ]
        present = ["Sample"] + [c for c in tax_cols if c in taxonomy.columns]
        merged = data_analysis.merge(
            taxonomy[present], how="left",
            left_on="ID", right_on="Sample", suffixes=("", "_tax"),
        )
        for c in tax_cols:
            tax_col = f"{c}_tax"
            if tax_col in merged.columns:
                # Prefer taxonomy.csv values; fall back to data_analysis ones.
                merged[c] = merged[tax_col].where(
                    merged[tax_col].astype(bool), merged.get(c, "")
                )
                merged.drop(columns=[tax_col], inplace=True)
        if "Sample" in merged.columns:
            merged.drop(columns=["Sample"], inplace=True)
        data_analysis = merged.fillna("")

    copla_path = run_dir / "copla_modif.csv"
    copla = (
        pd.read_csv(copla_path, sep=",", dtype=str).fillna("")
        if copla_path.exists()
        else pd.DataFrame()
    )
    integrons_path = run_dir / "integron_summary.csv"
    integrons = (
        pd.read_csv(integrons_path, sep=",", dtype=str).fillna("")
        if integrons_path.exists()
        else pd.DataFrame()
    )
    return {
        "data_analysis": data_analysis,
        "copla": copla,
        "integrons": integrons,
    }


def run_ingestion(args: argparse.Namespace, repo: Repository) -> dict:
    """Ingest plasmids, integrons and host metadata of the current run.

    The function is tolerant to missing optional inputs: copla_modif.csv
    and integron_summary.csv are optional (their absence is logged and
    skipped), but data_analysis.tsv is required because host metadata is
    the backbone of every cross-run alert.
    """
    run_dir: Path = args.run_dir
    run_name: str = args.run_name

    inputs = _load_run_inputs(run_dir)
    data_analysis = inputs["data_analysis"]
    copla = inputs["copla"]
    integrons = inputs["integrons"]
    seq_dates = _load_seq_dates(run_dir)

    n_hosts = n_plasmids = n_integrons = 0
    n_plasmids_skipped_size = 0
    n_plasmids_skipped_missing = 0

    # ---- Hosts ----------------------------------------------------------
    for _, row in data_analysis.iterrows():
        isolate_id = row.get("ID", "")
        if not isolate_id:
            continue
        host_uid = make_host_uid(run_name, isolate_id)
        repo.ingest_host({
            "host_uid": host_uid,
            "run_name": run_name,
            "seq_date": seq_dates.get(isolate_id, ""),
            "lab_id": row.get("Lab_id", ""),
            "isolate_id": isolate_id,
            "strain": row.get("Strain", ""),
            "genus": row.get("Majority_genus", ""),
            "species": row.get("Majority_species", ""),
            "subspecies": row.get("Subspecies", ""),
            "mlst": row.get("MLST", ""),
            "serotype": row.get("Serotype", ""),
            "ko_locus": row.get("KO_locus", ""),
            "amr_score": row.get("AMRscore", ""),
            "vir_score": row.get("VIRscore", ""),
            "ingested_at": now_iso(),
        })
        n_hosts += 1

    # ---- Plasmids -------------------------------------------------------
    # MOB-suite emits per-plasmid FASTAs as
    #   08_Anotacion/<sample>/mob_recon/plasmid_<cluster_id>.fasta
    # and the Copla output uses the cluster_id as the "Contig" column. The
    # chromosome and unbinned contigs are intentionally ignored (the user
    # tracks chromosomal AMR via Kleborate / ABRicate on the assembly).
    for _, row in copla.iterrows():
        isolate_id = row.get("Sample", "")
        contig = row.get("Contig", "")
        if not isolate_id or not contig:
            continue
        try:
            size = int(row.get("Size", "0") or 0)
        except ValueError:
            size = 0
        if size and size < args.min_plasmid_size:
            n_plasmids_skipped_size += 1
            continue
        host_uid = make_host_uid(run_name, isolate_id)
        fasta = (
            run_dir / "08_Anotacion" / isolate_id / "mob_recon"
            / f"plasmid_{contig}.fasta"
        )
        uid = repo.ingest_plasmid(
            host_uid, contig, fasta,
            metadata={
                "run_name": run_name,
                "sample_id": isolate_id,
                "ptu": row.get("PTU", ""),
                "rep": row.get("Rep", ""),
                "mob": row.get("MOB", ""),
                "mpf": row.get("MPF", ""),
                "size": size,
                "amr_genes": row.get("AbR", ""),
                "vir_genes": row.get("Vir", ""),
            },
        )
        if uid is None:
            n_plasmids_skipped_missing += 1
        else:
            n_plasmids += 1

    # ---- Integrons ------------------------------------------------------
    # Each row of integron_summary.csv is one integron on one contig of one
    # sample. Cassette columns give the (ordered) gene list which we collapse
    # into an unordered set for Jaccard matching (P3 decision).
    for _, row in integrons.iterrows():
        isolate_id = row.get("Sample", "")
        contig = row.get("Pl/Chr", "")
        try:
            start = int(row.get("Start", "0") or 0)
            end = int(row.get("End", "0") or 0)
        except ValueError:
            continue
        if not isolate_id or not contig or start <= 0 or end <= 0:
            continue

        host_uid = make_host_uid(run_name, isolate_id)
        gene_set = _parse_cassette_gene_set(row)
        # Integrons are AMR-bearing by construction in clinical isolates;
        # we mirror the cassette gene set into amr_genes so the P4 relevance
        # filter can read a single uniform field across MGE types.
        amr_genes_str = ";".join(sorted(gene_set))

        assembly = run_dir / "03_assemblies" / f"{isolate_id}.fasta"
        uid = repo.ingest_integron(
            host_uid, contig, start, end, assembly,
            metadata={
                "run_name": run_name,
                "sample_id": isolate_id,
                "integron_type": row.get("Type", ""),
                "integrase": row.get("Integrase", ""),
                "gene_set_json": serialize_gene_set(gene_set),
                "amr_genes": amr_genes_str,
                "vir_genes": "",
            },
        )
        if uid is not None:
            n_integrons += 1

    # ---- Sketch rebuild -------------------------------------------------
    repo.update_plasmid_sketch()

    return {
        "hosts": n_hosts,
        "plasmids": n_plasmids,
        "plasmids_skipped_size": n_plasmids_skipped_size,
        "plasmids_skipped_missing_fasta": n_plasmids_skipped_missing,
        "integrons": n_integrons,
    }


def run_matching(args: argparse.Namespace, repo: Repository) -> list[dict]:
    """Match each MGE of the current run against the repository's prior state.

    Must be called *before* :func:`run_ingestion` so the repo snapshot does
    not contain the current run yet (otherwise every plasmid would trivially
    match itself). Returns a list of match-record dicts; one record per
    ``(current_mge, repo_mge)`` pair. P4 consumes these to apply the
    relevance filter and emit ``alerts.tsv``.

    Plasmids are matched at two levels: tuple-coarse (same PTU/Rep/MOB and
    size within ``args.size_tolerance``) and identity-fine (skani ANI
    >= ``args.ani_threshold``). A UID that fires at the identity level is
    labeled ``"identity"``; UIDs that fire only at the tuple level are
    labeled ``"type"``. Integrons are matched only by Jaccard on the
    cassette gene set (>= ``args.jaccard_threshold``).
    """
    run_dir: Path = args.run_dir
    run_name: str = args.run_name

    inputs = _load_run_inputs(run_dir)
    data_analysis = inputs["data_analysis"]
    copla = inputs["copla"]
    integrons = inputs["integrons"]

    # Current-run host metadata indexed by isolate ID for quick lookup when
    # building match records. Same shape as hosts.tsv but in memory and
    # restricted to the current run.
    current_hosts: dict[str, dict] = {}
    for _, row in data_analysis.iterrows():
        isolate_id = row.get("ID", "")
        if not isolate_id:
            continue
        current_hosts[isolate_id] = {
            "host_uid": make_host_uid(run_name, isolate_id),
            "run_name": run_name,
            "lab_id": row.get("Lab_id", ""),
            "isolate_id": isolate_id,
            "genus": row.get("Majority_genus", ""),
            "species": row.get("Majority_species", ""),
            "subspecies": row.get("Subspecies", ""),
            "mlst": row.get("MLST", ""),
            "serotype": row.get("Serotype", ""),
            "ko_locus": row.get("KO_locus", ""),
            "amr_score": row.get("AMRscore", ""),
            "vir_score": row.get("VIRscore", ""),
        }

    repo_hosts = repo.load_hosts().set_index("host_uid", drop=False) if not repo.load_hosts().empty else None

    records: list[dict] = []

    # ---- Plasmid matching ----------------------------------------------
    for _, row in copla.iterrows():
        isolate_id = row.get("Sample", "")
        contig = row.get("Contig", "")
        if not isolate_id or not contig:
            continue
        try:
            size = int(row.get("Size", "0") or 0)
        except ValueError:
            size = 0
        if size and size < args.min_plasmid_size:
            continue

        current_meta = {
            "ptu": row.get("PTU", ""),
            "rep": row.get("Rep", ""),
            "mob": row.get("MOB", ""),
            "mpf": row.get("MPF", ""),
            "size": size,
            "amr_genes": row.get("AbR", ""),
            "vir_genes": row.get("Vir", ""),
        }

        # Tuple-level matches.
        df_tuple = repo.find_plasmid_matches_by_tuple(
            current_meta["ptu"], current_meta["rep"], current_meta["mob"],
            size, size_tolerance=args.size_tolerance,
        )
        tuple_uids = set(df_tuple["uid"]) if not df_tuple.empty else set()

        # Identity-level matches via skani. Query FASTA is the MOB-suite
        # output from the current run (not yet ingested into the repo).
        query_fasta = (
            run_dir / "08_Anotacion" / isolate_id / "mob_recon"
            / f"plasmid_{contig}.fasta"
        )
        df_ani = repo.find_plasmid_matches_by_ani(
            query_fasta, min_ani=args.ani_threshold,
        )
        identity_uids = set(df_ani["uid"]) if not df_ani.empty else set()
        ani_by_uid = (
            dict(zip(df_ani["uid"], df_ani["ani"])) if not df_ani.empty else {}
        )

        all_uids = tuple_uids | identity_uids
        for uid in all_uids:
            # Identity wins over type when a UID fires at both levels.
            if uid in identity_uids:
                level = "identity"
                score = float(ani_by_uid.get(uid, 0.0))
            else:
                level = "type"
                score = 1.0
            repo_row = (
                df_ani[df_ani["uid"] == uid].iloc[0].to_dict()
                if uid in identity_uids
                else df_tuple[df_tuple["uid"] == uid].iloc[0].to_dict()
            )
            repo_host_row = (
                repo_hosts.loc[repo_row["host_uid"]].to_dict()
                if (repo_hosts is not None and repo_row["host_uid"] in repo_hosts.index)
                else {}
            )
            records.append({
                "mge_type": "plasmid",
                "current_isolate_id": isolate_id,
                "current_contig": contig,
                "current_host": current_hosts.get(isolate_id, {}),
                "current_meta": current_meta,
                "match_uid": uid,
                "match_level": level,
                "score": score,
                "repo_row": repo_row,
                "repo_host": repo_host_row,
            })

    # ---- Integron matching ---------------------------------------------
    for _, row in integrons.iterrows():
        isolate_id = row.get("Sample", "")
        contig = row.get("Pl/Chr", "")
        try:
            start = int(row.get("Start", "0") or 0)
            end = int(row.get("End", "0") or 0)
        except ValueError:
            continue
        if not isolate_id or not contig or start <= 0 or end <= 0:
            continue
        gene_set = _parse_cassette_gene_set(row)
        if not gene_set:
            continue

        df_j = repo.find_integron_matches_by_jaccard(
            gene_set, min_jaccard=args.jaccard_threshold,
        )
        if df_j.empty:
            continue

        current_meta = {
            "integron_type": row.get("Type", ""),
            "integrase": row.get("Integrase", ""),
            "gene_set": sorted(gene_set),
            "gene_set_json": serialize_gene_set(gene_set),
            "amr_genes": ";".join(sorted(gene_set)),  # cassettes are AMR-bearing
            "vir_genes": "",
            "size": end - start + 1,
            "start": start,
            "end": end,
        }

        for _, jrow in df_j.iterrows():
            repo_host_row = (
                repo_hosts.loc[jrow["host_uid"]].to_dict()
                if (repo_hosts is not None and jrow["host_uid"] in repo_hosts.index)
                else {}
            )
            records.append({
                "mge_type": "integron",
                "current_isolate_id": isolate_id,
                "current_contig": contig,
                "current_host": current_hosts.get(isolate_id, {}),
                "current_meta": current_meta,
                "match_uid": jrow["uid"],
                "match_level": f"jaccard:{jrow['jaccard']:.2f}",
                "score": float(jrow["jaccard"]),
                "repo_row": jrow.to_dict(),
                "repo_host": repo_host_row,
            })

    return records


