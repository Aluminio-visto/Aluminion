# Auto-translate legacy Spanish column headers (Cultivo, Cepa, ID, Barcode, Conc, Repetida)
# to the current English schema. Earlier versions of the pipeline shipped Spanish names;
# this keeps old lab sheets working without forcing the user to edit them manually.
# Field order is preserved — only the header row is rewritten.
#
# Detection is by CONTENT, not by an exact prefix: the anchored '^(Cultivo|Cepa)\b'
# this used to test failed on the sheets the lab actually exports from Excel, whose
# first field is "Nº Cultivo" (and third "ID único" — accented, with a space). The
# header was therefore left in Spanish, aluminion_reporter.py's key_col='ID' never
# matched, no 'Sample' column was created, and the run died at the QC merge with
# KeyError: 'Sample' AFTER every sample had already been assembled and annotated.
# So: match if any known Spanish marker appears anywhere in the header line, and
# require that the English schema is NOT already in place.
list_header=$(head -n 1 list_seq.tsv | tr -d '\r')
# NOTE: the guard uses $'\t' (bash ANSI-C quoting), not '\t' inside the pattern —
# GNU grep -E does not honour \t as an escape, it matches a literal 't', so
# '(^|\t)Lab_id' would silently never match the English header.
if ! echo "$list_header" | grep -qE "^Lab_id($(printf '\t')|$)" \
   && echo "$list_header" | grep -qiE 'Cultivo|Cepario|Cepa|ID[[:space:]]*(único|unico)|Repetir|\[DNA\]'; then
    warn "list_seq.tsv uses legacy Spanish column names — auto-translating to English (Lab_id, Strain, ID, Barcode, DNA_conc, is_repeated)."
    {
        echo -e "Lab_id\tStrain\tID\tBarcode\tDNA_conc\tis_repeated"
        tail -n +2 list_seq.tsv | tr -d '\r'
    } > list_seq.tsv.translated
    mv list_seq.tsv.translated list_seq.tsv
fi

# With MinKNOW import skipped, the run folder must already contain a populated
# fastq_pass/. Otherwise, copy only the barcode subfolders referenced in
# list_seq.tsv (col 4) from the MinKNOW data tree into <run>/fastq_pass/.
# `tr -d '\r'` strips CRLF line endings that appear when list_seq.tsv is exported
# from Excel on Windows — without it, "01\r" would not match any printf %02d output.
if [ -n "$NO_MINKNOW" ]; then
    # fastq_pass/ is only ever dereferenced later by the read-concatenation loop
    # inside the preprocessing block, and only for a sample where resume_done() is
    # false. It is NOT needed at all when --skip-preprocessing is set (that block
    # never runs), and it is not needed under --resume if every listed sample
    # already has its concatenated reads staged in 01_reads/<id>.fastq.gz (e.g. a
    # project where reads were concatenated and named by hand or by an external
    # pipeline, never through this script's own fastq_pass/ import). Don't demand
    # fastq_pass/ in those cases — it would never be read anyway.
    _fastq_pass_needed=true
    if [ -n "$SKIP_PREPROCESSING" ]; then
        _fastq_pass_needed=false
    elif [ -n "$RESUME" ]; then
        _fastq_pass_needed=false
        while IFS=$'\t' read -r _fp_cult _fp_cep _fp_id _fp_bc _fp_dna _fp_rep; do
            [ -z "$_fp_id" ] && continue
            if [ ! -s "01_reads/${_fp_id}.fastq.gz" ]; then
                _fastq_pass_needed=true
                break
            fi
        done < <(tail -n +2 list_seq.tsv | tr -d '\r')
    fi
    if [ "$_fastq_pass_needed" = true ] && { [ ! -d "fastq_pass" ] || [ -z "$(ls -A fastq_pass 2>/dev/null)" ]; }; then
        error_log "--skip-import-from-minknow set but ${WORKDIR}/fastq_pass/ is missing or empty."
        error_log "Either populate fastq_pass/ with per-barcode subfolders, drop --skip-import-from-minknow,"
        error_log "or — if 01_reads/<ID>.fastq.gz is already staged for every sample — add --resume so the"
        error_log "read-concatenation step is skipped and fastq_pass/ is never required."
        exit 1
    fi
    if [ -d "fastq_pass" ] && [ -n "$(ls -A fastq_pass 2>/dev/null)" ]; then
        log "Using existing fastq_pass/ inside the run folder (MinKNOW import skipped)."
    else
        log "fastq_pass/ not required: reads already staged in 01_reads/ (--resume) or --skip-preprocessing is set."
    fi
    unset _fastq_pass_needed
elif resume_done "fastq_pass/.minknow_import_done"; then
    # A previous run already imported every referenced barcode into fastq_pass/.
    # Re-copying with cp -r would overwrite identical files and thrash the disk for
    # no gain, so on --resume we trust the completed import and move on.
    log "  [resume] fastq_pass/ already imported from MinKNOW, skipping copy."
else
    mkdir -p fastq_pass
    # `|| true` after the pipeline (not just on `ls`) is required under
    # `set -o pipefail`: when the glob matches nothing, `ls` exits 2 (discarded to
    # /dev/null) and, even though the downstream `head -n1` exits 0, pipefail makes
    # the *pipeline's* status the rightmost non-zero — i.e. 2 — which propagated
    # into this command-substitution assignment and aborted the whole run via the
    # ERR trap, before ever reaching the "MinKNOW directory not found" warning
    # below that is supposed to handle exactly this (non-fatal) case.
    FASTQ_SRC=$(ls -d "${MINKNOW_DIR}/${RUN_NAME}/no_sample_id/"*/fastq_pass 2>/dev/null | head -n1 || true)
    if [ -n "$FASTQ_SRC" ]; then
        tail -n +2 list_seq.tsv \
            | tr -d '\r' \
            | awk -F'\t' '{gsub(/^[[:space:]]+|[[:space:]]+$/, "", $4); print $4}' \
            | grep -Ev '^[[:space:]]*$|^[xX]$' \
            | sort -u \
            | while read -r bc; do
                # Force base-10: printf treats a leading-zero value like "08"/"09" as
                # octal, where 8 and 9 are invalid digits ("invalid octal number").
                # 10#$bc strips that interpretation so zero-padded barcodes work.
                padded=$(printf "%02d" "$((10#$bc))")
                src="${FASTQ_SRC}/barcode${padded}"
                if [ -d "$src" ]; then
                    cp -r "$src" fastq_pass/
                else
                    log "Warning: barcode${padded} not found in MinKNOW fastq_pass — skipping."
                fi
            done
        # Mark the import complete so a later --resume skips it. Written only after the
        # copy loop, so an interrupted import (no sentinel) is correctly retried.
        touch fastq_pass/.minknow_import_done
    else
        log "Warning: MinKNOW fastq_pass directory not found. Continuing without copying reads."
    fi
fi

