# 1. Read preparation and QC/filtering
if [ -z "$SKIP_PREPROCESSING" ]; then
    echo -e "ID\tR1\tR2\tLongFastQ\tFast5\tGenomeSize\tFasta" > samplesheet.tsv

    # Strip CRLF (Excel-exported TSVs) before reading fields. Without this, the last
    # field of each line keeps a trailing \r that breaks printf, file lookups, and grep.
    tail -n +2 list_seq.tsv | tr -d '\r' | while IFS=$'\t' read -r cult cep id bc c rep; do
        [ -z "$id" ] && continue
        # Trim leading/trailing whitespace from the barcode in case the TSV has padded cells.
        bc="${bc#"${bc%%[![:space:]]*}"}"
        bc="${bc%"${bc##*[![:space:]]}"}"
        # Zero-pad barcode to match MinKNOW's two-digit directory naming (barcode01, barcode09…).
        # The copy step above already pads with printf "%02d"; this keeps the two in sync.
        # 10#$bc forces base-10 so a zero-padded "08"/"09" is not misread as octal.
        padded_bc=$(printf "%02d" "$((10#$bc))")
        if resume_done "01_reads/${id}.fastq.gz"; then
            log "  [resume] Read concat: ${id} already done, skipping."
        elif [ -z "$rep" ]; then
            # Fresh sample — concatenate the per-barcode FASTQs from this run only.
            cat fastq_pass/barcode${padded_bc}/*.fastq.gz > 01_reads/${id}.fastq.gz
            if [ -z "$UNIQUE_RUN" ]; then
                cp 01_reads/${id}.fastq.gz "${REPO}/01_reads/${id}.fastq.gz"
            fi
        else
            # is_repeated sample. In repository-aware mode, prepend the prior reads
            # stored in the shared repository. Under --unique-run (or when the
            # repository exists but lacks prior reads for this sample), fall back to
            # the new reads alone and warn so the user knows the merge didn't happen.
            if [ -z "$UNIQUE_RUN" ] && [ -f "${REPO}/01_reads/${id}.fastq.gz" ]; then
                cat "${REPO}/01_reads/${id}.fastq.gz" fastq_pass/barcode${padded_bc}/*.fastq.gz > 01_reads/${id}.fastq.gz
                cp 01_reads/${id}.fastq.gz "${REPO}/01_reads/${id}.fastq.gz"
            else
                if [ -n "$UNIQUE_RUN" ]; then
                    warn "  Sample ${id} is marked is_repeated but --unique-run is active — using new reads only (no concat with the repository)."
                else
                    warn "  Sample ${id} is marked is_repeated but no prior reads found in the repository — using new reads only."
                fi
                cat fastq_pass/barcode${padded_bc}/*.fastq.gz > 01_reads/${id}.fastq.gz
                if [ -z "$UNIQUE_RUN" ]; then
                    cp 01_reads/${id}.fastq.gz "${REPO}/01_reads/${id}.fastq.gz"
                fi
            fi
        fi
        echo -e "${id}\t\t\t$PWD/01_reads/${id}.fastq.gz\t\t" >> samplesheet.tsv
    done
    # Build the sample list as the INTERSECTION of (a) the IDs declared in
    # list_seq.tsv and (b) the per-sample FASTQs on disk that pass the size filter.
    #
    # Scanning 01_reads/ alone (the old behaviour) made `samples` a function of disk
    # state instead of the sample sheet, so list_seq.tsv was authoritative only on a
    # sample's FIRST pass. Once 01_reads/<id>.fastq.gz existed, deleting a row from
    # list_seq.tsv had no effect: the find picked the leftover FASTQ back up and every
    # --resume re-queued the sample for assembly. That is exactly how a sample removed
    # from the sheet kept being handed to Flye. Intersecting makes the sheet
    # authoritative on every pass — dropping a row now really drops the sample —
    # while keeping the size filter as the quality gate it was meant to be.
    awk -F'\t' 'NR>1 {gsub(/^[[:space:]]+|[[:space:]]+$/, "", $3); if ($3 != "") print $3}' \
        list_seq.tsv | tr -d '\r' | sort -u > .listed_ids
    find 01_reads -type f -name "*.fastq.gz" -size "+${MIN_READ_MB}M" -exec basename {} .fastq.gz \; \
        | sort -u > .reads_on_disk
    # Stage the new list, then validate it BEFORE replacing `samples`. Writing the find
    # result straight into `samples` destroyed it whenever the scan came back empty —
    # which is the normal state of a completed run whose 01_reads/ was pruned by the
    # end-of-run cleanup. A --resume over such a run (e.g. a loop re-resuming every
    # historical run) truncated `samples` to zero rows and then aborted, losing the
    # record of which samples the run contained.
    comm -12 .listed_ids .reads_on_disk > .samples_new

    # Reads present and big enough, but no longer declared in the sheet: almost always
    # a row the user deliberately removed (bad sequencing, contaminated sample). Say so
    # explicitly, because silently ignoring a 400MB FASTQ would otherwise look like a bug.
    dropped_ids=$(comm -13 .listed_ids .reads_on_disk | tr '\n' ' ')
    if [ -n "${dropped_ids// /}" ]; then
        log "Reads on disk not listed in list_seq.tsv — excluded from this run: ${dropped_ids}"
    fi
    rm -f .listed_ids .reads_on_disk

    if [ ! -s .samples_new ]; then
        rm -f .samples_new
        if [ -s samples ]; then
            error_log "No reads in 01_reads/ pass the ${MIN_READ_MB}MB filter, but this run already has a"
            error_log "'samples' file with $(wc -l < samples) sample(s) — the reads were most likely pruned by the"
            error_log "end-of-run cleanup. The existing 'samples' file was left untouched."
            error_log "Regenerate the reads with --just-preprocessing, or re-run with --skip-preprocessing"
            error_log "to reuse the existing results without touching the reads."
        else
            error_log "No samples in list_seq.tsv have reads in 01_reads/ passing the ${MIN_READ_MB}MB filter."
        fi
        exit 1
    fi
    mv .samples_new samples

    conda activate aluminion_reads

    # Chrome (used by NanoPlot's plot renderer) requires --no-sandbox on headless Linux servers.
    # Glob across the common conda installations (mambaforge / miniforge3 / miniconda3) so
    # the wrapper works regardless of which conda flavour the user installed.
    CHROME_REAL=""
    for conda_root in "$HOME/mambaforge" "$HOME/miniforge3" "$HOME/miniconda3"; do
        # `ls` returns 2 when the glob has no match; under `set -o pipefail` that
        # exit code propagates through `| head -1` and kills the script via `set -e`
        # before the loop can try the next conda root. `|| true` neutralises it.
        candidate=$(ls "$conda_root/envs/aluminion_reads/lib/python"*/site-packages/choreographer/cli/browser_exe/chrome-linux64/chrome 2>/dev/null | head -1 || true)
        if [ -n "$candidate" ]; then
            CHROME_REAL="$candidate"
            break
        fi
    done
    if [ -n "$CHROME_REAL" ] && [ -x "$CHROME_REAL" ]; then
        CHROME_WRAPPER="${WORKDIR}/.chrome_wrapper"
        printf '#!/bin/bash\nexec "%s" --no-sandbox --disable-gpu --disable-dev-shm-usage "$@"\n' "$CHROME_REAL" > "$CHROME_WRAPPER"
        chmod +x "$CHROME_WRAPPER"
        export BROWSER_PATH="$CHROME_WRAPPER"
    fi

    # Prefer pigz for (de)compression when present — it parallelises the gzip stage
    # that otherwise bottlenecks each Chopper pipe on a single core. Falls back to
    # gzip/gunzip so a run on an env without pigz still works unchanged.
    if command -v pigz >/dev/null 2>&1; then
        DECOMP="pigz -dc"; COMP="pigz -p ${THREADS_FILTER}"
    else
        DECOMP="gunzip -c"; COMP="gzip"
    fi

    log "Filtering (Chopper, up to ${PAR_FILTER} samples in parallel)..."
    par_reset
    for i in $(cat samples); do
        resume_done "02_filter/${i}.fastq.gz" && { log "  [resume] Chopper: ${i} done, skipping."; continue; }
        # Each pipe writes only its own 02_filter/${i}.fastq.gz, so concurrent jobs
        # cannot corrupt each other. Bounded by PAR_FILTER to keep the mechanical-disk
        # read/write streams from thrashing. Per-job threads reduced (THREADS_FILTER).
        {
            $DECOMP 01_reads/${i}.fastq.gz \
                | chopper -q $CHOPPER_MIN_QUALITY -l $CHOPPER_MIN_LENGTH --headcrop $CHOPPER_HEADCROP --threads $THREADS_FILTER \
                | $COMP > 02_filter/${i}.fastq.gz
        } &
        par_wait "$PAR_FILTER"
    done
    par_drain
    # Background pipes cannot trip set -e, so verify every expected output exists and
    # is non-empty; a silent chopper/gzip failure would otherwise surface as an obscure
    # truncated-gzip error deep inside Kraken2 or Flye.
    for i in $(cat samples); do
        [ -s "02_filter/${i}.fastq.gz" ] \
            || { error_log "Chopper produced no output for ${i}. Check the integrity of 01_reads/${i}.fastq.gz."; exit 1; }
    done

    # Read QC (NanoPlot) for both pre- and post-filter FASTQs. These plots are only
    # consumed at the final consolidation step, so we launch them as a bounded
    # background pool here and let them overlap the long Kraken2 + assembly phase,
    # then drain them before annotation. NanoPlot downsamples to 20k reads, so the
    # extra disk pressure during assembly is negligible.
    # (Previously both loops used bare `&` with NO wait and NO bound — a latent race
    # that launched all samples at once and only worked because assembly happened to
    # outlast NanoPlot. par_wait bounds it; the par_drain before annotation fixes it.)
    log "Read QC (NanoPlot, up to ${PAR_QC} samples in parallel, overlaps assembly)..."
    par_reset
    for i in $(cat samples); do
        resume_done "01_reads/QC/${i}/NanoStats.txt" && continue
        MPLBACKEND=Agg NanoPlot --fastq 01_reads/${i}.fastq.gz -o 01_reads/QC/${i} --downsample 20000 --threads 4 --loglength &
        par_wait "$PAR_QC"
    done
    for i in $(cat samples); do
        resume_done "02_filter/QC/${i}/NanoStats.txt" && continue
        MPLBACKEND=Agg NanoPlot --fastq 02_filter/${i}.fastq.gz -o 02_filter/QC/${i} --downsample 20000 --threads 4 --loglength &
        par_wait "$PAR_QC"
    done
else
    log "Skipping preprocessing — using existing reads and QC from previous run."
    if [ ! -s "samples" ]; then
        error_log "'samples' file not found. Re-run without --skip-preprocessing first."
        exit 1
    fi
    # The default end-of-run cleanup prunes 01_reads/ and 02_filter/ (regenerable from
    # fastq_pass/). If a previous complete run pruned them, --skip-preprocessing has
    # nothing to reuse — fail early with a clear pointer instead of an obscure
    # "file not found" deep inside Kraken2/Flye. Regenerate with --just-preprocessing.
    missing_reads=()
    for i in $(cat samples); do
        [ -s "02_filter/${i}.fastq.gz" ] || missing_reads+=("$i")
    done
    if [ ${#missing_reads[@]} -gt 0 ]; then
        error_log "--skip-preprocessing set but filtered reads are missing for: ${missing_reads[*]}"
        error_log "They were likely pruned by the end-of-run cleanup (fastq_pass/ is kept on purpose)."
        error_log "Regenerate them first with --just-preprocessing, then re-run with --skip-preprocessing."
        exit 1
    fi
fi

