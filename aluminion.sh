# Returns true if --resume is active and the sentinel file or directory already exists
resume_done() { [ -n "$RESUME" ] && { [ -f "$1" ] || [ -d "$1" ]; }; }

# Returns true if --resume is active and EVERY named path exists as a regular,
# non-empty FILE. Use this — never resume_done on a directory — whenever the
# output directory is created by the tool (or by our own `mkdir -p`) *before* the
# work inside it finishes. `resume_done <dir>` is true the instant a sample
# starts, so a sample interrupted mid-run (Ctrl-C, OOM, power cut, a batch moving
# on after an error) is silently treated as complete on the next --resume, and its
# missing results are then indistinguishable from a genuine biological negative.
# That exact failure mode cost us Phastest samples (see phastest_done) and the
# same shape exists for every directory-sentinel step.
resume_files_done() {
    [ -n "$RESUME" ] || return 1
    local f
    for f in "$@"; do
        [ -s "$f" ] || return 1
    done
    return 0
}

# ------------------------------------------------------------------------------
# Bounded-concurrency helper for embarrassingly-parallel per-sample steps.
# ------------------------------------------------------------------------------
# Many per-sample steps (NanoPlot, Chopper, Abricate, MOB-suite, Copla) are
# independent and light enough that running them one-by-one leaves most cores
# idle. This helper overlaps a bounded number of them at once. CPU-saturating
# steps that already use every core (Flye, Bakta, dorado polish, Integron_Finder)
# are deliberately NOT parallelised — doing so would only oversubscribe the CPU.
#
# IMPORTANT: background jobs run in subshells, so a job body CANNOT mutate parent
# shell state (the failed_* arrays). Only use this for steps whose job body writes
# solely to its own per-sample output files and needs no parent bookkeeping.
#
# Usage:
#     par_reset                                   # before the loop
#     for i in ...; do { work "$i"; } & par_wait <MAX>; done
#     par_drain                                   # after the loop (or later)
#
# Implementation: track the PIDs of the jobs WE launch in an array, and wait only on
# those specific PIDs — never a bare `wait`/`wait -n`.
#   * Why not `while (( $(jobs -rp|wc -l) >= MAX ))`: command substitution `$(...)` forks
#     a subshell with an EMPTY job table, so `jobs` there always reports zero and the
#     throttle never engages.
#   * Why not a bare `wait` in par_drain: stdout/stderr are piped to a `tee -a` child via
#     `exec > >(tee ...)` (process substitution). A bare `wait` (and `wait -n` with no
#     args) also waits on that logger child, which never exits until the script ends — so
#     the pipeline HANGS FOREVER. It is most visible on --resume, when every per-sample
#     step is skipped, no jobs are launched, and tee is the only remaining child. Waiting
#     on explicit PIDs sidesteps tee and any unrelated background job entirely.
# par_wait blocks on the OLDEST in-flight PID (FIFO) when at cap; `wait <pid>` works on
# every bash (unlike `wait -n <pid...>`, which needs bash >= 5.1). For these homogeneous,
# light per-sample jobs the head-of-line cost is negligible. set -e safety: a finished
# job's non-zero exit would abort the run under errexit, so we swallow it with `|| true`;
# each job body is responsible for its own errors.
_par_pids=()
par_reset() { _par_pids=(); }
par_wait()  {
    # Must be called immediately after `... &` so $! is that job's PID.
    _par_pids+=("$!")
    if [ "${#_par_pids[@]}" -ge "$1" ]; then
        wait "${_par_pids[0]}" 2>/dev/null || true
        _par_pids=("${_par_pids[@]:1}")          # drop the reaped (oldest) PID
    fi
}
par_drain() {
    [ "${#_par_pids[@]}" -gt 0 ] && wait "${_par_pids[@]}" 2>/dev/null || true
    _par_pids=()
}

# Prune large, non-reusable intermediates after a fully completed run. Disabled by
# --keep-everything. Only ever called at the very end of a complete run (the early
# --just-* exits return before this point), so the deleted files are no longer needed
# by any downstream step. fastq_pass/ is intentionally retained, which is what makes
# the per-sample reads in 01_reads/ and 02_filter/ disposable: they can be regenerated
# from fastq_pass/ with --just-preprocessing. All removals are per-sample and use -f/-rf
# so a missing target (e.g. a sample that skipped an optional step) is a silent no-op.
cleanup_run_artifacts() {
    log "Pruning intermediate files to save disk (pass --keep-everything to retain them)..."
    local i
    for i in $(cat samples 2>/dev/null); do
        # Flye staging directories (assembly graph + final assembly.fasta are kept)
        rm -rf "03_assemblies/${i}/00-assembly" \
               "03_assemblies/${i}/10-consensus" \
               "03_assemblies/${i}/20-repeat" \
               "03_assemblies/${i}/30-contigger" \
               "03_assemblies/${i}/40-polishing" \
               "03_assemblies/${i}/deconcat/multimer_mapping"
        # BLASTn nucleotide DBs: the ISfinder screen builds one on
        # 08_Anotacion/<s>/mob_recon/chromosome.fasta (sidecar *.n* files), and
        # deconcat builds per-contig DBs under 03_assemblies/<s>/deconcat/blastn/.
        rm -f "08_Anotacion/${i}/mob_recon/chromosome.fasta".n*
        rm -rf "03_assemblies/${i}/deconcat/blastn"
        # Kraken2 per-read classification stream (the .report summary is kept)
        rm -f "04_taxonomies/kraken2/${i}.out"
        # Per-sample reads — regenerable from the retained fastq_pass/ via --just-preprocessing
        rm -f "01_reads/${i}.fastq.gz" "02_filter/${i}.fastq.gz"
    done
    rm -rf .temp_dorado_models*
}

